"use client";

import { useState } from "react";
import FilterListIcon from "@mui/icons-material/FilterList";
import { Dropdown } from "@/features/admin/components/dropdown";
import { Badge, Card, DataTable, SearchInput } from "@/shared/components/ui";

type GeneratedReport = {
  id: string;
  title: string;
  type: string;
  source: string;
  status: string;
  generated_by: string;
  generated_at: string;
};

function getStatusVariant(status: string) {
  switch (status) {
    case "ready":
      return "success" as const;
    case "queued":
      return "warning" as const;
    case "review_needed":
      return "danger" as const;
    default:
      return "default" as const;
  }
}

function formatStatus(status: string) {
  return status.replace("_", " ");
}

function formatDate(value: string) {
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? value : date.toLocaleDateString();
}

export function GeneratedReportsTable({ reports }: { reports: GeneratedReport[] }) {
  const [search, setSearch] = useState("");
  const [typeFilter, setTypeFilter] = useState("all");
  const [statusFilter, setStatusFilter] = useState("all");
  const [sortOrder, setSortOrder] = useState("latest");

  const types = [...new Set(reports.map((report) => report.type))];
  const statuses = [...new Set(reports.map((report) => report.status))];

  const filtered = reports
    .filter((report) => {
      const searchTerm = search.toLowerCase();
      const matchesSearch =
        report.title.toLowerCase().includes(searchTerm) ||
        report.source.toLowerCase().includes(searchTerm) ||
        report.generated_by.toLowerCase().includes(searchTerm);
      const matchesType = typeFilter === "all" || report.type === typeFilter;
      const matchesStatus = statusFilter === "all" || report.status === statusFilter;

      return matchesSearch && matchesType && matchesStatus;
    })
    .sort((a, b) => {
      const diff = new Date(b.generated_at).getTime() - new Date(a.generated_at).getTime();
      return sortOrder === "latest" ? diff : -diff;
    });

  return (
    <Card padded={false} className="flex flex-1 flex-col overflow-hidden">
      <div className="flex flex-wrap items-center gap-3 border-b border-[#E4EEF9] px-6 py-4">
        <h2 className="text-lg font-black text-[#0C2B49]">All Generated Reports</h2>
        <div className="ml-auto flex flex-wrap items-center gap-3">
          <SearchInput
            aria-label="Search generated reports"
            placeholder="Search report, source, owner..."
            value={search}
            onChange={(event) => setSearch(event.target.value)}
            className="w-56"
          />
          <Dropdown
            icon={<FilterListIcon fontSize="small" className="text-[#5B6F8A]" />}
            value={typeFilter}
            onChange={setTypeFilter}
            options={[{ label: "All Types", value: "all" }, ...types.map((type) => ({ label: type, value: type }))]}
          />
          <Dropdown
            value={statusFilter}
            onChange={setStatusFilter}
            options={[
              { label: "All Status", value: "all" },
              ...statuses.map((status) => ({
                label: formatStatus(status).replace(/\b\w/g, (char) => char.toUpperCase()),
                value: status,
              })),
            ]}
          />
          <Dropdown
            value={sortOrder}
            onChange={setSortOrder}
            options={[
              { label: "Latest", value: "latest" },
              { label: "Oldest", value: "oldest" },
            ]}
          />
        </div>
      </div>
      <DataTable
        ariaLabel="Generated reports"
        columns={[
          { key: "title", label: "Report", render: (report) => <span className="font-semibold text-[#0C2B49]">{report.title}</span> },
          { key: "type", label: "Type", render: (report) => <Badge>{report.type}</Badge> },
          { key: "source", label: "Source", render: (report) => <span className="text-[#5B6F8A]">{report.source}</span> },
          { key: "status", label: "Status", render: (report) => <Badge variant={getStatusVariant(report.status)}>{formatStatus(report.status)}</Badge> },
          { key: "generatedBy", label: "Generated By", render: (report) => <span className="text-[#0C2B49]">{report.generated_by}</span> },
          { key: "date", label: "Generated", render: (report) => <span className="text-[#5B6F8A] tabular-nums">{formatDate(report.generated_at)}</span> },
        ]}
        data={filtered}
        keyExtractor={(report) => report.id}
        emptyMessage="No generated reports found."
      />
    </Card>
  );
}
